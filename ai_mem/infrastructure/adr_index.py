"""Regenerate docs/records/INDEX.md -- a compact record/title/status table over ADR files, each record a relative link.

Pure storage-layer artifact, regenerated by `mem lint --fix` and by
FileMemoryRepository whenever a record file appears/vanishes or an INDEX row changes.
"""
from __future__ import annotations

import sys
from pathlib import Path

from ai_mem.domain.memory import title_of
from ai_mem.infrastructure import adr_markdown
from ai_mem.infrastructure.adr_paths import iter_record_files, write_atomic
from ai_mem.infrastructure.record_links import area_of_records_dir, href_for_ref

_INDEX_FILENAME = "INDEX.md"


def render_index(adr_dir: Path, report_skipped: bool = True) -> str:
    """The INDEX.md text for every `*.md` file below `adr_dir`, except the
    top-level INDEX.md/README.md (same-named files in subfolders are ordinary records).

    A malformed file is skipped and reported by name (stderr, unless `report_skipped` is
    off) rather than aborting the run, Rows are
    sorted by id and the field order is fixed, so output is byte-identical across runs
    given unchanged sources.
    """
    rows: list[tuple[str, str, str, str, str, str]] = []
    for file_path in iter_record_files(adr_dir):
        try:
            parsed = adr_markdown.parse(file_path.read_text(), entry_id=file_path.stem)
        except ValueError as exc:
            if report_skipped:
                print(f"skipping {file_path.relative_to(adr_dir)}: {exc}", file=sys.stderr)
            continue

        status = "active"
        if parsed.superseded_by:
            status = f"superseded_by: {_link(adr_dir, parsed.superseded_by)}"
        link = f"[{parsed.id}]({file_path.relative_to(adr_dir).as_posix()})"
        rows.append((parsed.id, link, parsed.area, parsed.type, title_of(parsed.text), status))

    rows.sort(key=lambda row: row[0])

    lines = ["# Decision Records Index", "", "| record | topic | type | title | status |", "|---|---|---|---|---|"]
    lines.extend(f"| {link} | {topic} | {entry_type} | {title} | {status} |" for _, link, topic, entry_type, title, status in rows)
    return "\n".join(lines) + "\n"


def _link(adr_dir: Path, ref: str) -> str:
    """`[name](path)` for a reference, relative to INDEX.md."""
    try:
        href = href_for_ref(adr_dir / _INDEX_FILENAME, area_of_records_dir(adr_dir), ref)
    except ValueError:
        return ref
    return f"[{adr_markdown.href_stem(href)}]({href})"


def index_is_current(adr_dir: Path) -> bool:
    """Whether the existing INDEX.md equals what `regenerate_index` would write (unreadable = no)."""
    try:
        current = (adr_dir / _INDEX_FILENAME).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False
    return current == render_index(adr_dir, report_skipped=False)


def regenerate_index(adr_dir: Path) -> None:
    """Rebuild `<adr_dir>/INDEX.md` (see `render_index`)."""
    # Full rescan, not read-modify-write: two concurrent writers each produce a complete table and
    # the swap is atomic. A writer that scanned before another writer's file landed can leave a
    # stale table; it heals on the next regeneration.
    write_atomic(adr_dir / _INDEX_FILENAME, render_index(adr_dir))

